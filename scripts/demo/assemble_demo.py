#!/usr/bin/env python3
"""Assemble the rag-docs-chatbot demo from the raw screen recording.

The raw capture is cut at the narration scene boundaries, padded by one
transition length at the end of every scene except the last, and joined with
FFmpeg ``xfade`` transitions. Padding each outgoing scene means the crossfade
overlaps a held frame instead of consuming timeline, so the final video keeps
the narration's exact duration.

The narration track is built by placing each clip at its scene start. No
captions or subtitle stream is written: the finished file carries the voice
track only.

Inputs (generated by scripts/demo/record_demo.py and the TTS step):
  video-work/rag-raw.webm
  /tmp/rag-demo-tts/holds.json
  /tmp/rag-demo-tts/00.mp3 .. 08.mp3

Outputs:
  video-work/rag-docs-chatbot-demo.mp4
  video-work/rag-docs-chatbot-demo-poster.jpg
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORK = ROOT / "video-work"
TTS = Path("/tmp/rag-demo-tts")
DEFAULT_TRANSITION = 0.35
WIDTH = 1920
HEIGHT = 1080
FPS = 30


def run(command: list[str]) -> None:
    subprocess.run(command, check=True)


def ffmpeg(*args: str) -> None:
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args])


def probe_duration(path: Path) -> float:
    result = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=nw=1:nk=1",
            str(path),
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    return float(result.stdout.strip())


def build_narration(
    clips: list[Path], starts: list[float], total: float, output: Path
) -> None:
    inputs: list[str] = []
    for clip in clips:
        inputs.extend(["-i", str(clip)])

    filters: list[str] = []
    for index, start in enumerate(starts):
        delay_ms = int(round(start * 1000))
        filters.append(
            f"[{index}:a]aresample=48000,"
            "aformat=sample_fmts=fltp:channel_layouts=stereo,"
            f"adelay={delay_ms}:all=1[a{index}]"
        )
    filters.append(
        "".join(f"[a{index}]" for index in range(len(clips)))
        + f"amix=inputs={len(clips)}:duration=longest:normalize=0[amixed]"
    )
    filters.append(
        f"[amixed]apad=whole_dur={total:.3f},"
        f"atrim=duration={total:.3f}[aout]"
    )

    ffmpeg(
        *inputs,
        "-filter_complex",
        ";".join(filters),
        "-map",
        "[aout]",
        "-ar",
        "48000",
        "-c:a",
        "aac",
        "-b:a",
        "160k",
        str(output),
    )


def cut_scene(raw: Path, start: float, duration: float, output: Path, pad: float) -> None:
    filters = [
        f"fps={FPS}",
        f"scale={WIDTH}:{HEIGHT}:force_original_aspect_ratio=decrease",
        f"pad={WIDTH}:{HEIGHT}:(ow-iw)/2:(oh-ih)/2",
        "setsar=1",
        "format=yuv420p",
        f"trim=duration={duration:.3f}",
        "setpts=PTS-STARTPTS",
    ]
    if pad > 0:
        filters.append(f"tpad=stop_mode=clone:stop_duration={pad:.3f}")
    ffmpeg(
        "-ss",
        f"{start:.3f}",
        "-i",
        str(raw),
        "-t",
        f"{duration + pad:.3f}",
        "-vf",
        ",".join(filters),
        "-an",
        "-c:v",
        "libx264",
        "-preset",
        "veryfast",
        "-crf",
        "16",
        "-pix_fmt",
        "yuv420p",
        "-r",
        str(FPS),
        str(output),
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--transition",
        type=float,
        default=DEFAULT_TRANSITION,
        help=f"xfade length in seconds (default: {DEFAULT_TRANSITION})",
    )
    parser.add_argument(
        "--raw",
        type=Path,
        default=WORK / "rag-raw.webm",
        help="raw Playwright recording (default: video-work/rag-raw.webm)",
    )
    parser.add_argument(
        "--holds",
        type=Path,
        default=TTS / "holds.json",
        help="timeline JSON from record_demo.py (default: /tmp/rag-demo-tts/holds.json)",
    )
    parser.add_argument(
        "--tts",
        type=Path,
        default=TTS,
        help="directory with 00.mp3..08.mp3 (default: /tmp/rag-demo-tts)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=WORK / "rag-docs-chatbot-demo.mp4",
        help="finished MP4 (default: video-work/rag-docs-chatbot-demo.mp4)",
    )
    parser.add_argument(
        "--poster",
        type=Path,
        default=WORK / "rag-docs-chatbot-demo-poster.jpg",
        help="poster JPEG (default: video-work/rag-docs-chatbot-demo-poster.jpg)",
    )
    parser.add_argument(
        "--poster-at",
        type=float,
        default=None,
        help="poster timestamp in seconds (default: scene 1 after the answer)",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    holds_path = args.holds
    for required in (args.raw, holds_path):
        if not required.exists():
            raise SystemExit(f"missing input: {required}")

    timeline = json.loads(holds_path.read_text())
    holds = [float(value) for value in timeline["holds"]]
    starts = [float(value) for value in timeline["scene_starts"]]
    if len(holds) != len(starts):
        raise SystemExit("holds.json has mismatched holds and scene_starts")
    total = float(timeline.get("total") or sum(holds))

    clips = [args.tts / f"{index:02d}.mp3" for index in range(len(starts))]
    for clip in clips:
        if not clip.exists():
            raise SystemExit(f"missing narration clip: {clip}")

    WORK.mkdir(parents=True, exist_ok=True)
    narration = WORK / "rag-demo-narration.m4a"
    build_narration(clips, starts, total, narration)
    print(f"narration: {probe_duration(narration):.3f}s", file=sys.stderr)

    segments_dir = WORK / "segments"
    segments_dir.mkdir(exist_ok=True)
    for stale in segments_dir.glob("rag-scene-*.mp4"):
        stale.unlink()

    segments: list[Path] = []
    last = len(holds) - 1
    for index, (start, hold) in enumerate(zip(starts, holds)):
        segment = segments_dir / f"rag-scene-{index:02d}.mp4"
        cut_scene(
            args.raw,
            start,
            hold,
            segment,
            args.transition if index < last else 0.0,
        )
        actual = probe_duration(segment)
        segments.append(segment)
        print(
            f"scene {index:02d}: {actual:.3f}s (planned {hold:.3f}s)",
            file=sys.stderr,
        )

    inputs: list[str] = []
    durations: list[float] = []
    for segment in segments:
        inputs.extend(["-i", str(segment)])
        durations.append(probe_duration(segment))

    filters: list[str] = []
    label = "0:v"
    current = durations[0]
    for index in range(1, len(segments)):
        next_label = f"v{index}"
        offset = max(0.0, current - args.transition)
        filters.append(
            f"[{label}][{index}:v]xfade=transition=fade:"
            f"duration={args.transition:.3f}:offset={offset:.3f}[{next_label}]"
        )
        label = next_label
        current += durations[index] - args.transition

    silent = WORK / "rag-demo-transitions.mp4"
    ffmpeg(
        *inputs,
        "-filter_complex",
        ";".join(filters),
        "-map",
        f"[{label}]",
        "-an",
        "-c:v",
        "libx264",
        "-preset",
        "slow",
        "-crf",
        "18",
        "-pix_fmt",
        "yuv420p",
        "-r",
        str(FPS),
        "-movflags",
        "+faststart",
        str(silent),
    )

    ffmpeg(
        "-i",
        str(silent),
        "-i",
        str(narration),
        "-map",
        "0:v:0",
        "-map",
        "1:a:0",
        "-c:v",
        "libx264",
        "-preset",
        "slow",
        "-crf",
        "20",
        "-pix_fmt",
        "yuv420p",
        "-r",
        str(FPS),
        "-c:a",
        "aac",
        "-b:a",
        "160k",
        "-movflags",
        "+faststart",
        "-t",
        f"{total:.3f}",
        str(args.output),
    )

    if args.poster_at is not None:
        poster_at = args.poster_at
    elif "poster_at" in timeline:
        poster_at = float(timeline["poster_at"])
    else:
        poster_at = starts[1] + holds[1] * 0.75
    if not 0 <= poster_at < total:
        raise SystemExit(
            f"poster timestamp {poster_at:.3f}s is outside the {total:.3f}s video"
        )

    ffmpeg(
        "-ss",
        f"{poster_at:.3f}",
        "-i",
        str(args.output),
        "-frames:v",
        "1",
        "-q:v",
        "2",
        str(args.poster),
    )

    print(f"video:  {args.output} ({probe_duration(args.output):.3f}s)")
    print(f"poster: {args.poster} ({poster_at:.3f}s)")


if __name__ == "__main__":
    main()
